#!/usr/bin/env bash
set -euo pipefail
source scripts/safe-mode.sh

OUT_DIR="modules/genom/out"
PR_MD="$OUT_DIR/pr_draft.md"
DIFF_JSON="$OUT_DIR/diff.json"
CODE_DIR="code"

mkdir -p "$OUT_DIR"

# Always allowed meta outputs
ts=$(date -Iseconds)
cat > "$PR_MD" <<MD
# PR Draft — $ts
Action: harden

## Goals
- policy guard hardening
- module tests
- coverage +5%

## Proposed Changes
- Update POLICY thresholds if hardening
- Add/extend module tests
- Improve logging/observability

> Generated by Helix Guided Fixes
MD

cat > "$DIFF_JSON" <<JSON
{"generated_at":"$ts","changes":[{"path":"docs/TASKS.md","type":"update"}]}
JSON

echo "✅ Genom: meta artifacts updated → $PR_MD, $DIFF_JSON"

# Skip writing to project code when SAFE_MODE=1
if [ "${SAFE_MODE}" = "1" ]; then
  echo "⚠️  Safe Mode: skipping code generation into $CODE_DIR/"
  exit 0
fi

# (Normal mode) — demo scaffold write
mkdir -p "$CODE_DIR"
echo "Hello from Genom @ $ts" > "$CODE_DIR/HELLO.txt"
echo "✅ Genom: wrote scaffold → $CODE_DIR/HELLO.txt"
